// FINN, READ STRAIGHT THROUGH (Kong, 2026-10-16: "I want to edit all of
// Finn's lines on the fishing side"): every word Finn says in the Long Cast,
// in the order a captain meets it, as the Godot port shows it (the web's
// tables with port_rules laid over them, the port's own jobs slotted in), into
// one Markdown file to read and mark up.
//
//   node godot/game/tools/finn_script.mjs [out.md]
//   (default: docs/finn-script.md)

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const GAME = path.join(HERE, '..')
const OUT = process.argv[2] || path.join(GAME, '..', '..', 'docs', 'finn-script.md')
const rules = JSON.parse(fs.readFileSync(path.join(GAME, 'content', 'rules.json'), 'utf8'))
const port = JSON.parse(fs.readFileSync(path.join(GAME, 'content', 'port_rules.json'), 'utf8'))

// The port's merge (core/rules.gd _merge): dictionaries merge, anything else
// (arrays included) replaces; keys starting "_" are notes.
function merge(a, b) {
  for (const [k, v] of Object.entries(b || {})) {
    if (k.startsWith('_')) continue
    if (a[k] && typeof a[k] === 'object' && !Array.isArray(a[k]) && v && typeof v === 'object' && !Array.isArray(v)) merge(a[k], v)
    else a[k] = structuredClone(v)
  }
  return a
}

const finn = merge(structuredClone(rules.finn), port.finn)
const ancient = merge(structuredClone(rules.finnAncientBeats || {}), port.finnAncientBeats)

// The ladder as core/finn.gd quests() lays it: each port job after the job it names.
const quests = []
for (const q of finn.quests) {
  quests.push(q)
  for (const e of finn.portJobs || []) if (e.after === q.id) quests.push({ ...e, port: true })
}

const L = []
const say = (s = '') => L.push(s)
const clean = s => String(s ?? '').replace(/\*/g, '_')
const lines = ls => {
  for (const l of ls || []) {
    const t = typeof l === 'string' ? l : l.text
    const p = typeof l === 'object' && l.pause ? `  _(holds ${l.pause}ms)_` : ''
    say(`- ${clean(t)}${p}`)
  }
}

say('# Finn: every line on the fishing side')
say()
say('Everything Finn says in the Long Cast, as the Godot game shows it. Generated by `godot/game/tools/finn_script.mjs`; edits go in `content/port_rules.json` (`finn`, `finnAncientBeats`), not here. Mark this file up and the changes are carried over.')
say()
say('Key: **First, the story** is what he tells you before he sets the job (the beat). **Gives it** is what he says setting the job. **Not yet** is what he says while it is open. **Done** is what he says when it is handed back. **Too soon** is what he says when your level is not there yet. A job marked _(port)_ is one the Godot game added. _Italics_ in his lines are his emphasis.')
say()

// core/finn.gd: the story runs one rung at a time. At the first meeting, and
// each time a job is handed back, he says the next beat he has not said (in
// the beats' own order) and then gives the next job. So the Nth beat leads
// into the Nth job.
const beats = finn.beats

let n = 0
for (const ch of finn.chapters) {
  say(`## Chapter ${ch.romanNumeral}: ${clean(ch.title)}`)
  say()
  say(`_Opens at Fishing ${ch.minLevel}. ${clean(ch.subtitle)}_`)
  say()
  for (const q of quests.filter(q => q.band === ch.band)) {
    const b = beats[n]
    n++
    say(`### Job ${n}: ${clean(q.label)}  \`${q.id}\`${q.port ? ' _(port)_' : ''}`)
    say()
    if (b) {
      say(`**First, the story** \`${b.id}\`:`)
      lines(b.lines)
      say()
    }
    if (q.give) say(`**Gives it:** ${clean(q.give)}`), say()
    if (q.hint) say(`**His description (on the slip):** "${clean(q.hint)}"`), say()
    if (q.waiting) say(`**Not yet:** ${clean(q.waiting)}`), say()
    if (q.done) say(`**Done:** ${clean(q.done)}`), say()
    if (q.gated) say(`**Too soon** (this job is next, but your level is not there yet): ${clean(q.gated)}`), say()
  }
}
const late = beats.slice(n)
if (late.length) {
  say('## Story past the last job')
  say()
  for (const b of late) {
    say(`### \`${b.id}\``)
    say()
    lines(b.lines)
    say()
  }
}

say('## Every job')
say()
say('**When it is done and you come to him:** You have got it. Go on then, hand it over.')
say()

say('## What you can ask him')
say()
say('Questions that open as he warms to you, one set per standing. You ask, he answers.')
say()
finn.asks.forEach((set, i) => {
  say(`### Standing: ${clean(finn.standingName[i])}`)
  say()
  for (const a of set || []) say(`- **You:** ${clean(a.you)}`), say(`  **Finn:** ${clean(a.they)}`)
  say()
})

say('## When he has nothing new to say')
say()
lines(finn.idle)
say()

say('## The first giant: the reveal')
say()
say('After your first trophy from the Ancient Deep.')
say()
lines((finn.reveal || {}).lines)
say()

say('## Each giant landed')
say()
const NAMES = { 143: 'Megalodon', 144: 'Plesiosaurus', 145: 'Dunkleosteus', 146: 'Mosasaurus', 147: 'Basilosaurus', 148: 'Shastasaurus' }
for (const [id, b] of Object.entries(ancient)) {
  say(`### ${NAMES[id] || id}  \`${id}\``)
  say()
  lines(b.lines)
  if (b.ctaLabel) say(`- _(button: ${clean(b.ctaLabel)})_`)
  say()
}

say('## After the six')
say()
say('**When you hail him:**')
lines(finn.epilogueIdle)
say()
say('**Now and then, a story:**')
lines(finn.epilogueLore)
say()

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, L.join('\n'))
console.log(`${quests.length} jobs, ${finn.beats.length} beats, ${L.length} lines -> ${OUT}`)
