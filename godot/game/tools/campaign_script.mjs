// THE CAMPAIGN, READ STRAIGHT THROUGH (Kong, 2026-10-16): every word the
// expedition campaign shows, in order, as the Godot port shows it (the web's
// tables with port_rules laid over them: campaignText, raids, bossTitles,
// retiredNodes), into one Markdown file to read and mark up.
//
//   node godot/game/tools/campaign_script.mjs [out.md]
//   (default: docs/campaign-script.md)

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const GAME = path.join(HERE, '..')
const OUT = process.argv[2] || path.join(GAME, '..', '..', 'docs', 'campaign-script.md')
const rules = JSON.parse(fs.readFileSync(path.join(GAME, 'content', 'rules.json'), 'utf8'))
const port = JSON.parse(fs.readFileSync(path.join(GAME, 'content', 'port_rules.json'), 'utf8'))

// The port's merge (core/rules.gd _merge): dictionaries merge, anything else
// (arrays included) replaces; keys starting "_" are notes.
function merge(a, b) {
  for (const [k, v] of Object.entries(b || {})) {
    if (k.startsWith('_')) continue
    if (a[k] && typeof a[k] === 'object' && !Array.isArray(a[k]) && v && typeof v === 'object' && !Array.isArray(v)) merge(a[k], v)
    else a[k] = structuredClone(v)
  }
  return a
}

const retired = new Set(port.retiredNodes || [])
const nodes = rules.campaign.nodes.filter(n => !retired.has(n.id)).map(n => merge(structuredClone(n), (port.campaignText || {})[n.id]))
const raids = structuredClone(rules.raids)
for (const [id, r] of Object.entries(port.raids || {})) merge(raids[id] = raids[id] || {}, r)
const titles = port.bossTitles || {}
const chapters = rules.campaign.chapters

const L = []
const say = (s = '') => L.push(s)
// The port capitalises "the Don" as it loads (core/rules.gd _the_don); so does this.
const clean = s => String(s ?? '').replace(/\*/g, '_').replace(/\b([Tt])he don(?![a-z]|['’]t)/g, '$1he Don')

say('# Seas the Booty: the campaign, start to finish')
say()
say('Every word the expedition campaign shows, in the order a captain meets it, exactly as the Godot game shows it. Generated by `godot/game/tools/campaign_script.mjs`; edits go in `content/port_rules.json`, not here.')
say()
say('Key: **Chart card** is the line on the chart. **Card** is the node\'s sheet. **Captain\'s Log** is the line after it is cleared. A scene is its lines in order; _italics_ are narration.')
say()

let ch = 0
const chapterOf = id => chapters.findIndex(c => c.lastNodeId === id)
const heading = c => c.romanNumeral ? `Chapter ${c.romanNumeral}: ${c.title}` : c.title
say(`## ${heading(chapters[0])}`)
say()
say(`_${clean(chapters[0].subtitle)}_`)
say()

for (const n of nodes) {
  const d = n.detail || {}
  say(`### ${clean(n.label)}  \`${n.id}\` · ${n.type}`)
  say()
  if (n.flavor) say(`**Chart card:** ${clean(n.flavor)}`), say()
  if (d.description) say(`**Card:** ${clean(d.description).replace(/\n\n/g, ' / ')}`), say()
  const scene = n.scene || []
  if (scene.length) {
    if (n.cinema) say(`_(Played on the live sea: ${n.cinema}.)_`), say()
    for (const l of scene) {
      if (l.speaker) say(`- **${clean(l.speaker)}:** ${clean(l.text)}`)
      else say(`- _${clean(l.text).replace(/_/g, '')}_`)
      if (l.choice) say(`  - _Choice: ${l.choice.join(' / ')}_`)
    }
    say()
  }
  const r = n.raidId ? raids[n.raidId] : null
  if (r) {
    const boss = (r.enemies || {})[r.bossId] || {}
    const t = titles[String(n.raidId).replace(/_challenge$/, '')]
    say(`**The fight:** ${clean(r.raidTitle)}. Boss: ${clean(boss.name)}${t ? ` (${t})` : ''}.`)
    say()
    const pre = r.preFightDialogue || []
    if (pre.length && !/_challenge$/.test(n.raidId)) {
      say('**Before the boss round:**')
      for (const l of pre) {
        const who = l.speaker === 'boss' ? boss.name : l.speaker === 'crew' ? (l.crew || {}).name : null
        say(who ? `- **${clean(who)}:** ${clean(l.text)}` : `- _${clean(l.text).replace(/_/g, '')}_`)
      }
      say()
    }
    const ph = (boss.phases || []).filter(p => p.dialogueLine)
    if (ph.length && !/_challenge$/.test(n.raidId)) {
      say('**His line at each phase:**')
      for (const p of ph) say(`- ${clean(p.badge)}: ${clean(p.dialogueLine)}`)
      say()
    }
  }
  if (d.summary) say(`**Card once read:** ${clean(d.summary)}`), say()
  if (n.bridge) say(`**Captain's Log:** ${clean(n.bridge)}`), say()
  const c = chapterOf(n.id)
  if (c >= 0 && chapters[c + 1]) {
    say(`## ${heading(chapters[c + 1])}`)
    say()
    say(`_${clean(chapters[c + 1].subtitle)}_`)
    say()
  }
}

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, L.join('\n'))
console.log(`${nodes.length} nodes, ${L.length} lines -> ${OUT}`)
