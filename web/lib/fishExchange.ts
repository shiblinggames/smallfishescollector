// ── Quoting ─────────────────────────────────────────────────────────────────

export type Quote = {
  leverage: number
  /** The move, in percent, at which the contract returns exactly the stake. */
  breakEvenPct: number
}

export function quoteFund(members: number, term: Term): Quote {
  const leverage = fundLeverage(members, term)
  return { leverage, breakEvenPct: 1 / leverage }
}

export function quoteSingle(rarity: number, term: Term): Quote {
  const leverage = (SINGLE_LEVERAGE[rarity] ?? SINGLE_LEVERAGE[3])[term]
  return { leverage, breakEvenPct: 1 / leverage }
}

/** What a contract pays, given how far the instrument actually moved.
 *
 *  A move against you, or a move your way that never cleared break-even, pays
 *  LESS than the stake, down to nothing. There is no partial refund: this is
 *  the "expires worthless" end of the contract and it has to be able to reach
 *  zero, or the whole thing is a savings account. */
export function settlePayout(stake: number, entry: number, exit: number, dir: Direction, q: Quote): number {
  const movePct = ((exit - entry) / entry) * 100
  const yourWay = dir === 'rise' ? movePct : -movePct
  if (yourWay <= 0) return 0
  return Math.max(0, Math.round(stake * q.leverage * yourWay))
}

